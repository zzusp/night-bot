import {test,expect} from '@playwright/test'
import {startPreview} from './preview.mjs'
let fixture: Awaited<ReturnType<typeof startPreview>>
test.beforeAll(async()=>{fixture=await startPreview({port:0,sessionRecords:true})})
test.afterAll(async()=>{await fixture?.close()})
for(const width of [1440,390])test(`真实 HTTP 分诊路由标签与共享执行记录 ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.goto(fixture.origin+'/#/chat/sample-plan')
 await page.getByLabel('访问令牌',{exact:true}).fill(fixture.token)
 await page.getByRole('button',{name:'连接工作空间',exact:true}).click()
 const tabs=page.getByRole('tablist',{name:'会话记录'})
 await expect(tabs).toBeVisible()
 await page.locator('.board-composer textarea').fill('切换后保留的草稿')
 const first=page.getByRole('tab',{name:'对话',exact:true})
 await first.focus();await page.keyboard.press('ArrowRight')
 await expect(page.getByRole('tab',{name:'分诊',exact:true})).toBeFocused()
 const panel=page.getByRole('tabpanel',{name:'分诊',exact:true})
 await expect(panel.locator('.execution-history')).toBeVisible()
 await expect(panel).toContainText('channel_triage_submit')
 await expect(panel).toContainText('已提交本批分诊判断')
 await expect(panel).not.toContainText('一级分诊请求：')
 await page.screenshot({path:test.info().outputPath(`triage-${width}.png`)})
 await page.keyboard.press('ArrowRight')
 await expect(page.getByRole('tabpanel',{name:'路由',exact:true})).toContainText('resident_task_query')
 await expect(page.getByRole('tabpanel',{name:'路由',exact:true})).toContainText('已找到已有任务')
 await page.screenshot({path:test.info().outputPath(`router-${width}.png`)})
 await first.click();await expect(page.locator('.board-composer textarea')).toHaveValue('切换后保留的草稿')
 await page.goto(fixture.origin+'/#/channels/room-product')
 await page.getByRole('tab',{name:'分诊',exact:true}).click()
 await expect(page.getByRole('tabpanel',{name:'分诊',exact:true})).toContainText('channel_triage_submit')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.locator('.workspace-topbar').getByRole('button',{name:'切换深色外观'}).click()
 await page.screenshot({path:test.info().outputPath(`channel-triage-dark-${width}.png`)})
 await page.goto(fixture.origin+'/#/channels/room-empty')
 await expect(first).toHaveAttribute('aria-selected','true')
 await page.getByRole('tab',{name:'分诊',exact:true}).click()
 await expect(page.getByRole('heading',{name:'还没有分诊记录'})).toBeVisible()
 const empty=page.locator('.session-records-empty > .board-empty')
 const geometry=await empty.evaluate(el=>{const root=el.getBoundingClientRect();const icon=el.querySelector('.board-empty-icon')!.getBoundingClientRect();const title=el.querySelector('h2')!.getBoundingClientRect();return {dx:Math.abs((title.left+title.right)/2-(root.left+root.right)/2),dy:Math.abs((icon.top+title.bottom)/2-(root.top+root.bottom)/2)}})
 expect(geometry.dx).toBeLessThan(2);expect(geometry.dy).toBeLessThan(2)
 await page.screenshot({path:test.info().outputPath(`empty-triage-${width}.png`)})
 await page.getByRole('tab',{name:'路由',exact:true}).click()
 await expect(page.getByRole('heading',{name:'还没有路由记录'})).toBeVisible()
 await page.screenshot({path:test.info().outputPath(`empty-router-${width}.png`)})
})
test('切换终止旧记录读取，失败可重试且鉴权撤销清除正文',async({page})=>{
 await page.goto(fixture.origin+'/#/chat/sample-plan')
 await page.getByLabel('访问令牌',{exact:true}).fill(fixture.token)
 await page.getByRole('button',{name:'连接工作空间',exact:true}).click()
 await page.route('**/api/chat/sample-plan/triage/session?*',route=>route.fulfill({status:503,json:{error:{code:'SESSION_UNAVAILABLE'}}}))
 await page.getByRole('tab',{name:'分诊',exact:true}).click()
 await expect(page.getByRole('alert')).toBeVisible()
 await page.unroute('**/api/chat/sample-plan/triage/session?*')
 await page.getByRole('button',{name:'重新获取',exact:true}).click()
 await expect(page.getByRole('tabpanel',{name:'分诊',exact:true})).toContainText('已提交本批分诊判断')
 await page.route('**/api/chat/sample-plan/triage/session?*',route=>route.fulfill({status:403,json:{error:{code:'ACCESS_DENIED'}}}))
 await expect(page.getByRole('tabpanel',{name:'分诊',exact:true})).not.toContainText('已提交本批分诊判断',{timeout:10000})
 await page.getByRole('tab',{name:'路由',exact:true}).click()
 await expect(page.getByRole('tabpanel',{name:'路由',exact:true})).toContainText('已找到已有任务')
})
