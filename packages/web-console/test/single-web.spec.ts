import {test, expect} from '@playwright/test'
import {FIXTURE_TOKEN} from './preview.mjs'

test('Web主入口始终使用同一会话，旧入口正常输入但不能创建额外会话', async ({page, context}) => {
  await page.goto('/#/chat')
  await page.getByLabel('访问令牌', {exact: true}).fill(FIXTURE_TOKEN)
  await page.getByRole('button', {name: '连接工作空间', exact: true}).click()
  await expect(page.getByLabel('消息内容', {exact: true})).toBeEnabled()
  await expect(page.getByRole('button', {name: '新对话', exact: true})).toHaveCount(0)
  const current = await (await page.request.get('/api/chat-current')).json()
  expect(current.conversationId).toBe('sample-plan')
  const other = await context.newPage()
  await other.goto('/#/chat')
  await expect(other.getByLabel('消息内容', {exact: true})).toBeEnabled()
  expect(await (await other.request.get('/api/chat-current')).json()).toEqual(current)
  await page.evaluate(() => {location.hash = '/chat/sample-notes'})
  await expect(page.getByLabel('消息内容', {exact: true})).toBeEnabled()
  await expect(page.locator('.message-user')).toContainText('整理一份清晰的会议提纲')
  await page.getByLabel('消息内容', {exact: true}).fill('旧入口继续唯一Web对话')
  await page.getByRole('button', {name: '发送消息', exact: true}).click()
  await expect(page).toHaveURL(/\/#\/chat\/sample-plan$/)
  await expect(page.getByLabel('消息内容', {exact: true})).toBeEnabled()
  await page.evaluate(() => {location.hash = '/chat/arbitrary-new-id'})
  await expect(page.getByLabel('消息内容', {exact: true})).toBeDisabled()
  await expect(page.getByText('这条记录不存在，或已不再可用。')).toBeVisible()
  const recent = await (await page.request.get('/api/recent-conversations')).json()
  expect(recent.items.some((row: {kind: string}) => row.kind === 'channel')).toBe(true)
  await other.close()
})
